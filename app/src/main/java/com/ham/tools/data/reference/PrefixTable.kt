    /** 最长前缀优先，保证 3 字母前缀先于 2/1 字母命中。 */
    private val byLengthDesc: List<PrefixEntry> =
        entries.sortedByDescending { it.prefix.length }

    /**
     * 解析呼号。
     *
     * 规则：
     * - 忽略大小写与空格
     * - 斜杠后缀若本身是有效前缀（如 `W1AW/KH6` 的 `KH6`），优先按后缀判定操作地
     * - 否则按前缀最长匹配
     * - 常见的 `/P /M /MM /A /QRP` 等标记不参与实体判定
     */
    fun lookup(callsign: String): PrefixEntry? {
        val raw = callsign.trim().uppercase().replace(" ", "")
        if (raw.isEmpty()) return null

        // 斜杠后缀：只把它当作「操作地」线索，且仅当它是已知前缀时才采用
        val slash = raw.indexOf('/')
        if (slash > 0) {
            val suffix = raw.substring(slash + 1)
            val head = raw.substring(0, slash)
            if (suffix !in PORTABLE_MARKERS) {
                matchAt(suffix)?.let { return it }
            }
            return matchAt(head)
        }
        return matchAt(raw)
    }

    private fun matchAt(part: String): PrefixEntry? =
        byLengthDesc.firstOrNull { part.startsWith(it.prefix) }

    /**
     * 模糊检索：命中前缀、中文名或英文名。
     * 空关键词返回完整列表（按前缀排序）。
     */
    fun search(keyword: String): List<PrefixEntry> {
        val query = keyword.trim().lowercase()
        if (query.isEmpty()) return entries.sortedBy { it.prefix }
        return entries.filter { entry ->
            entry.prefix.lowercase().contains(query) ||
                entry.entity.lowercase().contains(query) ||
                entry.entityEn.lowercase().contains(query) ||
                (entry.note?.lowercase()?.contains(query) ?: false)
        }.sortedBy { it.prefix }
    }

    /** 按大洲筛选。 */
    fun filterByContinent(continent: String?): List<PrefixEntry> =
        if (continent.isNullOrEmpty()) entries.sortedBy { it.prefix }
        else entries.filter { it.continent == continent }.sortedBy { it.prefix }

    /** 这些斜杠后缀表示便携/移动操作，不改变实体归属。 */
    private val PORTABLE_MARKERS = setOf("P", "M", "MM", "AM", "A", "QRP", "PORTABLE", "MOBILE")
